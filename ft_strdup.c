#include "libft.h"

char	*ft_strdup(const char *s1)
{
	char		*copy;
	size_t		i;
	size_t		len;

	len = ft_strlen(s1);
	copy = malloc(len + 1);
	if (copy == NULL)
		return (NULL);
	i = 0;
	while (i < len)
	{
		copy[i] = s1[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
